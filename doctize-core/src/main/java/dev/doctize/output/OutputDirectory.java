package dev.doctize.output;

import dev.doctize.DoctizeException;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.stream.Stream;

/**
 * The directory the site is written to. Stale output of a previous run is removed, but only in a
 * directory that Doctize created itself (recognised by a marker file), so a mistyped output path
 * can never delete someone else's files.
 */
public final class OutputDirectory {

    private static final String MARKER = ".doctize-site";

    private final Path root;

    public OutputDirectory(Path root) {
        this.root = root.toAbsolutePath().normalize();
    }

    /** Prepares an empty directory, clearing the previous run's output if there is one. */
    public void prepare() {
        try {
            if (Files.exists(root.resolve(MARKER))) {
                deleteContents();
            }
            Files.createDirectories(root);
            Files.writeString(root.resolve(MARKER), "Generated by Doctize. Its contents are replaced on every run.\n");
        } catch (IOException e) {
            throw new DoctizeException("Cannot prepare output directory " + root + ": " + e.getMessage(), e);
        }
    }

    public void write(String relativePath, String content) {
        write(relativePath, content.getBytes(StandardCharsets.UTF_8));
    }

    public void write(String relativePath, byte[] content) {
        Path target = root.resolve(relativePath).normalize();
        if (!target.startsWith(root)) {
            throw new DoctizeException("Refusing to write outside of the output directory: " + relativePath);
        }
        try {
            Files.createDirectories(target.getParent());
            Files.write(target, content);
        } catch (IOException e) {
            throw new DoctizeException("Cannot write " + target + ": " + e.getMessage(), e);
        }
    }

    public void copy(String relativePath, Path source) {
        try {
            write(relativePath, Files.readAllBytes(source));
        } catch (IOException e) {
            throw new DoctizeException("Cannot read " + source + ": " + e.getMessage(), e);
        }
    }

    public Path root() {
        return root;
    }

    private void deleteContents() throws IOException {
        try (Stream<Path> walk = Files.walk(root)) {
            walk.sorted(Comparator.reverseOrder())
                    .filter(path -> !path.equals(root))
                    .forEach(OutputDirectory::delete);
        }
    }

    private static void delete(Path path) {
        try {
            Files.delete(path);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
